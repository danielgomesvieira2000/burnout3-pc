"""Writes port/gpu_pipelines.h: the GPU pipelines Burnout 3 draws with, for
ps2host::SetGpuPipelineHints - made in the background from the start, so a
player's first race makes none in the middle of it.

The keys come from the scripted runs, at the PS2's resolution and at 3x
(each run from an empty folder, with PS2HOST_PIPELINE_LOG=1, which logs
"[gpu] pipeline XXXXXXXX made ..." for each). Run again when the engine's
pipeline keys change (gs_renderer.cpp's PipelineKey and Features): keys of an
older engine are only made in vain.

    python make_pipeline_hints.py LOG_OR_KEY_FILE...
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "gpu_pipelines.h")


def main() -> None:
    keys = set()
    for path in sys.argv[1:]:
        with open(path, encoding="utf-8", errors="replace") as f:
            for line in f:
                m = re.search(r"pipeline ([0-9A-F]{8}) made", line) or re.fullmatch(r"\s*([0-9A-F]{8})\s*", line)
                if m:
                    keys.add(int(m.group(1), 16))
    if not keys:
        sys.exit("no keys found")
    rows = []
    ordered = sorted(keys)
    for i in range(0, len(ordered), 6):
        rows.append("    " + ", ".join("0x%08Xu" % k for k in ordered[i:i + 6]) + ",")
    text = (
        "/* Generated by tools/make_pipeline_hints.py from the scripted runs: the GPU\n"
        "   pipelines the game draws with, made in the background from the start\n"
        "   (ps2host::SetGpuPipelineHints). Not game material: the engine's own keys. */\n"
        "#pragma once\n\n"
        "#include <cstdint>\n\n"
        "constexpr std::uint32_t kGpuPipelineHints[] = {\n" + "\n".join(rows) + "\n};\n")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("%d keys -> %s" % (len(keys), os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
